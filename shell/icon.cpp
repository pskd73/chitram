static const uint8_t *findBitmap(const char *id) {
  if (!id || !id[0]) {
    return nullptr;
  }
  for (size_t i = 0; i < sizeof(kIcons) / sizeof(kIcons[0]); ++i) {
    if (strcmp(kIcons[i].id, id) == 0) {
      return kIcons[i].bitmap;
    }
  }
  return nullptr;
}

Icon::Icon(const char *id) : id_(id ? id : ""), bitmap_(findBitmap(id)) {}

bool Icon::exists(const char *id) { return findBitmap(id) != nullptr; }

bool Icon::draw(int16_t x, int16_t y, uint16_t color) const {
  if (!bitmap_) {
    return false;
  }
  int16_t y0, y1;
  if (!uiClipSpan(y, kSize, &y0, &y1)) {
    return true;
  }
  reclaimDisplay();
  const int first = y0 - y;
  const int rows = y1 - y0;
  if (first == 0 && rows == kSize) {
    tft.drawBitmap(x, y, bitmap_, kSize, kSize, color);
  } else {
    // 16-wide → 2 bytes per row
    tft.drawBitmap(x, y0, bitmap_ + first * 2, kSize, rows, color);
  }
  return true;
}

bool Icon::draw(int16_t x, int16_t y, uint16_t fg, uint16_t bg) const {
  if (!bitmap_) {
    return false;
  }
  int16_t y0, y1;
  if (!uiClipSpan(y, kSize, &y0, &y1)) {
    return true;
  }
  reclaimDisplay();
  const int first = y0 - y;
  const int rows = y1 - y0;
  if (first == 0 && rows == kSize) {
    tft.drawBitmap(x, y, bitmap_, kSize, kSize, fg, bg);
  } else {
    tft.drawBitmap(x, y0, bitmap_ + first * 2, kSize, rows, fg, bg);
  }
  return true;
}

bool Icon::draw(const char *id, int16_t x, int16_t y, uint16_t color) {
  return Icon(id).draw(x, y, color);
}

bool Icon::draw(const char *id, int16_t x, int16_t y, uint16_t fg,
                uint16_t bg) {
  return Icon(id).draw(x, y, fg, bg);
}
